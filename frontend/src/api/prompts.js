/** 明显越界时返回一句本地兜底回复，否则返回 null */
export function getLocalOffTopicReply(text) {
  const t = (text || '').trim()
  if (!t || t.length > 300) return null
  if (CREATIVE_HINTS.test(t)) return null // 带创作语境，交给模型判断
  if (!HARD_OFF_TOPIC.some((re) => re.test(t))) return null

  const pick = REDIRECTS[t.length % REDIRECTS.length]
  return `${OFF_TOPIC_PREFIX}${pick}`
}

/** 过滤历史消息，避免旧回复破坏规则 */
export function sanitizeHistory(history) {
  return (history || [])
    .filter((m) => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
    .map((m) => ({ role: m.role, content: m.content.slice(0, 1200) }))
    .slice(-12)
}
